import type { Exercise } from '../models/domain';

type IllustratedExercise = Pick<Exercise, 'name' | 'equipment' | 'muscleGroupId' | 'tags'>;

/** Local illustrations identify the movement family, not the exact grip or setup. */
export function exerciseIllustration(exercise?: IllustratedExercise): string {
  const name = (exercise?.name || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
  const rules: [RegExp, string][] = [
    [/wrist|avambracc/, 'wrist-curl'],
    [/leg curl.*seduto/, 'leg-curl-seated'],
    [/leg curl/, 'leg-curl'],
    [/leg extension/, 'leg-extension'],
    [/calf press/, 'calf-press'],
    [/calf.*seduto/, 'calf-seated'],
    [/calf|polpacc/, 'calf-raise'],
    [/leg press/, 'leg-press'],
    [/abductor/, 'abductor'],
    [/adductor/, 'adductor'],
    [/hip thrust|ponte glutei/, 'hip-thrust'],
    [/slanci glutei|donkey kick/, 'glute-kickback'],
    [/pull-through/, 'deadlift'],
    [/stacco/, 'deadlift'],
    [/step-up/, 'step-up'],
    [/affond|bulgaro/, 'lunge'],
    [/squat/, 'squat'],
    [/plank laterale/, 'side-plank'],
    [/plank|mountain climber/, 'plank'],
    [/bird dog/, 'bird-dog'],
    [/dead bug/, 'dead-bug'],
    [/ab wheel/, 'ab-wheel'],
    [/russian twist/, 'russian-twist'],
    [/sollevamento gambe|crunch inverso/, 'leg-raise'],
    [/crunch al cavo/, 'cable-crunch'],
    [/crunch/, 'crunch'],
    [/piegament/, 'push-up'],
    [/dip su panca/, 'bench-dip'],
    [/dip/, 'dip'],
    [/trazioni/, 'pull-up'],
    [/lat machine/, 'lat-pulldown'],
    [/pullover.*cavo|pulldown braccia/, 'cable-pullover'],
    [/pullover/, 'pullover'],
    [/pulley|rematore alla macchina/, 'seated-row'],
    [/rematore|t-bar/, 'bent-row'],
    [/estensioni lombari/, 'back-extension'],
    [/scrollat/, 'shrug'],
    [/face pull/, 'face-pull'],
    [/extrarotazion/, 'external-rotation'],
    [/tirate al mento/, 'upright-row'],
    [/alzate posteriori|reverse fly/, 'reverse-fly'],
    [/alzate frontali/, 'front-raise'],
    [/alzate laterali/, 'lateral-raise'],
    [/shoulder|military|arnold|spinte spalle/, 'shoulder-press'],
    [/chest press/, 'chest-press'],
    [/croci.*panca|croci manubri|croci con manubri|pectoral/, 'bench-fly'],
    [/croci/, 'cable-fly'],
    [/french press.*sopra|tricipiti.*sopra|estensioni tricipiti manubrio/, 'overhead-triceps'],
    [/french press/, 'french-press'],
    [/kickback tricipiti/, 'triceps-kickback'],
    [/pushdown|estensioni tricipiti/, 'triceps-pushdown'],
    [/curl.*scott|curl.*appoggio/, 'preacher-curl'],
    [/curl|bicipit/, 'biceps-curl'],
    [/panca.*declinat/, 'bench-decline'],
    [/panca.*inclinat|panca.*(?:15|30|45|60)°/, 'bench-incline'],
    [/panca|distensioni|squeeze press/, 'bench-press'],
  ];
  const movement = rules.find(([rule]) => rule.test(name))?.[1] || 'movement';
  return `/exercises/${movement}.svg`;
}
